// Isolated Electron regression for graph group membership after note renames.
const {app,BrowserWindow,ipcMain}=require('electron');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const ts=require('typescript');
const vm=require('node:vm');
const context={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root,'src/lib/graphPaths.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,context);
const {remapGraphPath,remapGraphPositions}=context.exports;
assert.equal(remapGraphPath('V/folder/A.md','V/folder','V/new'),'V/new/A.md');
assert.equal(remapGraphPath('V/folder2/A.md','V/folder','V/new'),'V/folder2/A.md');
assert.equal(remapGraphPath('Other/A.md','V/A.md','V/B.md'),'Other/A.md');
const moved=remapGraphPositions(new Map([['V/A.md',111],['V/B.md',0]]),'V/A.md','V/B.md');
assert.equal(moved.get('V/B.md'),111);
assert.equal(moved.has('V/A.md'),false);

const fixture=fs.mkdtempSync(path.join(root,'node_modules/.tmp/group-rename-'));
const vault=path.basename(fixture);
fs.writeFileSync(path.join(fixture,'Alpha.md'),'# Alpha\n[[Beta]]');
fs.writeFileSync(path.join(fixture,'Beta.md'),'# Beta');
const oldPath=`${vault}/Alpha.md`;
const groups=[{id:'g1',name:'First',color:'#818cf8',paths:[oldPath,`${vault}/Beta.md`]}, {id:'g2',name:'Second',color:'#f59e0b',paths:[oldPath]}, {id:'g3',name:'Other vault',color:'#34d399',paths:['Other/Alpha.md']}];
const links=[{id:'l1',fromId:'g1',toType:'node',toId:oldPath},{id:'l2',fromId:'g1',toType:'group',toId:'g2'}];
const pause=ms=>new Promise(r=>setTimeout(r,ms));
let main;
const js=(win,code)=>win.webContents.executeJavaScript(code);
async function until(win,code){for(let i=0;i<120;i++){if(await js(win,code))return;await pause(60);}throw new Error('Timed out: '+code);}
async function rename(title){
 await js(main,`(() => {const editor=document.querySelector('.tiptap-editor').editor;editor.commands.setContent({type:'doc',content:[{type:'heading',attrs:{level:1},content:[{type:'text',text:${JSON.stringify(title)}}]},{type:'paragraph',content:[{type:'text',text:'[[Beta]]'}]}]});editor.view.dom.dispatchEvent(new KeyboardEvent('keydown',{key:'s',ctrlKey:true,bubbles:true,cancelable:true}));})()`);
 await until(main,`document.querySelector('.tab-active')?.getAttribute('data-path')===${JSON.stringify(vault+'/'+title+'.md')}`);
 const current=await js(main,"JSON.parse(localStorage.getItem('papyrus-node-groups'))");
 assert.deepEqual(current[0],{...groups[0],paths:[`${vault}/${title}.md`,`${vault}/Beta.md`]});
 assert.deepEqual(current[1],{...groups[1],paths:[`${vault}/${title}.md`]});
 assert.deepEqual(current[2],groups[2]);
 assert.deepEqual(await js(main,"JSON.parse(localStorage.getItem('papyrus-group-links'))"),[{...links[0],toId:`${vault}/${title}.md`},links[1]]);
}
app.whenReady().then(async()=>{try{
 const preferences={preload:path.join(root,'electron/preload.cjs'),partition:'rename-'+Date.now(),backgroundThrottling:false};
 ipcMain.handle('get-app-version',()=> 'test');
 ipcMain.handle('open-directory-picker',()=>fixture);
 ipcMain.handle('fs-readdir',async(_,p)=>(await fs.promises.readdir(p,{withFileTypes:true})).map(e=>({name:e.name,isDirectory:e.isDirectory()})));
 ipcMain.handle('fs-readfile',(_,p)=>fs.promises.readFile(p,'utf8'));
 ipcMain.handle('fs-writefile',(_,p,text)=>fs.promises.writeFile(p,text));
 ipcMain.handle('fs-unlink',(_,p)=>fs.promises.unlink(p));
 ipcMain.handle('fs-exists',(_,p)=>fs.existsSync(p));
 main=new BrowserWindow({show:false,width:1200,height:800,webPreferences:preferences});
 main.webContents.setWindowOpenHandler(()=>({action:'allow',overrideBrowserWindowOptions:{show:false,webPreferences:preferences}}));
 await main.loadFile(path.join(root,'dist/index.html'));
 await js(main,`localStorage.setItem('papyrus-node-groups',${JSON.stringify(JSON.stringify(groups))});localStorage.setItem('papyrus-group-links',${JSON.stringify(JSON.stringify(links))})`);
 await main.reload();
 await until(main,"!!document.querySelector('.open-vault-btn')");
 await js(main,"document.querySelector('.open-vault-btn').click()");
 await until(main,"!!document.querySelector('[data-tooltip=\"Alpha.md\"]')");
 await js(main,"document.querySelector('[data-tooltip=\"Alpha.md\"]').closest('.tree-node-row').click();document.querySelectorAll('.sidebar-icon-btns button')[2].click()");
 await until(main,"!!document.querySelector('.tiptap-editor') && document.querySelectorAll('.graph-node').length===2");
 await js(main,`(() => {const c=new BroadcastChannel('papyrus-graph');c.postMessage({type:'nodePositions',data:{[${JSON.stringify(oldPath)}]:{x:111,y:222}}});c.close()})()`);
 await until(main,`[...document.querySelectorAll('.graph-node')].find(e=>e.__data__.id===${JSON.stringify(oldPath)})?.__data__.x===111`);
 await rename('Renamed');
 await until(main,`[...document.querySelectorAll('.graph-node')].find(e=>e.__data__.id===${JSON.stringify(vault+'/Renamed.md')})?.__data__.x===111`);
 assert.ok(!fs.existsSync(path.join(fixture,'Alpha.md')));
 await js(main,"document.querySelector('.graph-header-actions').lastElementChild.click()");
 await pause(150);
 const pip=BrowserWindow.getAllWindows().find(w=>w!==main);
 assert.ok(pip);
 await until(pip,"document.querySelectorAll('.graph-node').length===2");
 await rename('Again');
 await until(pip,`[...document.querySelectorAll('.group-hull')].filter(e=>e.__data__.paths.includes(${JSON.stringify(vault+'/Again.md')})).length===2`);
 await until(pip,`[...document.querySelectorAll('.graph-node')].find(e=>e.__data__.id===${JSON.stringify(vault+'/Again.md')})?.__data__.x===111`);
 await js(pip,"document.querySelector('.graph-header-actions button').click()");
 await until(main,"!!document.querySelector('.graph-panel')");
 await js(main,"document.querySelectorAll('.sidebar-icon-btns button')[2].click()");
 await until(main,"!document.querySelector('.graph-panel')");
 await rename('Hidden');
 await main.reload();
 await until(main,"!!document.querySelector('.open-vault-btn')");
 const restored=await js(main,"JSON.parse(localStorage.getItem('papyrus-node-groups'))");
 assert.ok(restored[0].paths.includes(`${vault}/Hidden.md`));
 assert.ok(restored[1].paths.includes(`${vault}/Hidden.md`));
 console.log('PASS: multiple groups, node/group links, docked coordinates, live PiP, hidden graph and reload persistence');
 app.exit(0);
}catch(e){console.error(e);app.exit(1)}});
setTimeout(()=>app.exit(2),45000);
